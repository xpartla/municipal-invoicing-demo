"""Running the Alembic migrations from code: `riso migrate`, the seed command and tests."""

from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory

from riso import paths
from riso.platform.db import create_db_engine

ALEMBIC_INI = paths.REPO_ROOT / "alembic.ini"


def alembic_config(url: str) -> Config:
    config = Config(str(ALEMBIC_INI))
    config.set_main_option("sqlalchemy.url", url)
    # Keep the caller's logging as it is; alembic.ini's logging is for the alembic CLI.
    config.attributes["configure_logger"] = False
    return config


def upgrade(url: str, revision: str = "head") -> None:
    command.upgrade(alembic_config(url), revision)


def downgrade(url: str, revision: str) -> None:
    command.downgrade(alembic_config(url), revision)


def check(url: str) -> None:
    """Raises `alembic.util.AutogenerateDiffsDetected` when the models and the migrated
    database differ."""
    command.check(alembic_config(url))


def current_revision(url: str) -> str | None:
    engine = create_db_engine(url)
    try:
        with engine.connect() as connection:
            return MigrationContext.configure(connection).get_current_revision()
    finally:
        engine.dispose()


def head_revision() -> str | None:
    return ScriptDirectory.from_config(Config(str(ALEMBIC_INI))).get_current_head()
